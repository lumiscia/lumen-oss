import { expect, test } from "vitest";

import { renderExpressions } from "../src/render-expressions.js";

const number = "number";

test("renders one documented function per builtin, with overloads for `same`", () => {
  const output = renderExpressions({
    globals: [{ name: "glyph_count", doc: "How many glyphs there are." }],
    builtins: [
      {
        name: "abs",
        minArgs: 1,
        maxArgs: 1,
        args: [{ name: "value", kind: number }],
        returns: number,
        doc: "Absolute value.",
      },
      {
        name: "spring",
        minArgs: 1,
        maxArgs: 3,
        args: [
          { name: "t", kind: number },
          { name: "stiffness", kind: number },
          { name: "in", kind: "easing" },
        ],
        returns: number,
        doc: "Spring from 0 to 1.",
      },
      {
        name: "concat",
        minArgs: 2,
        maxArgs: null,
        args: [{ name: "parts", kind: "text" }],
        returns: "string",
        doc: "Joins strings.",
      },
      {
        name: "key",
        minArgs: 2,
        maxArgs: 3,
        args: [
          { name: "at", kind: number },
          { name: "value", kind: "same" },
          { name: "ease", kind: "easing" },
        ],
        returns: "key",
        doc: "A keyframe.",
      },
      {
        name: "keyframes",
        minArgs: 2,
        maxArgs: null,
        args: [
          { name: "t", kind: number },
          { name: "ease", kind: "easing" },
          { name: "keys", kind: "key" },
        ],
        returns: "any",
        doc: "The value of keys at `t`.",
      },
    ],
  });

  expect(output)
    .toBe(`// Generated by tooling/generate-types from definitions/composition.schema.json.
// Do not edit by hand.

import { type Color, type Vec2 } from "@lumiscia/lumen-types";

import {
  call,
  Expr,
  type AnyArg,
  type Arg,
  type EasingArg,
  type Key,
  type KeyValue,
  type Num,
  type Vec3Value,
} from "../expression-core.js";

/**
 * How many glyphs there are.
 */
export const glyphCount = new Expr<number>("glyph_count");

/**
 * Absolute value.
 */
export function abs(value: Num): Expr<number> {
  return call("abs", [value]);
}

/**
 * Spring from 0 to 1.
 */
export function spring(t: Num, stiffness?: Num, in_?: EasingArg): Expr<number> {
  return call("spring", [t, stiffness, in_]);
}

/**
 * Joins strings.
 */
export function concat(
  parts: Arg<string> | Num,
  parts2: Arg<string> | Num,
  ...parts3: (Arg<string> | Num)[]
): Expr<string> {
  return call("concat", [parts, parts2, ...parts3]);
}

/**
 * A keyframe.
 */
export function key(at: Num, value: Num, ease?: EasingArg): Expr<Key<number>>;
/**
 * A keyframe.
 */
export function key(at: Num, value: Arg<Vec2>, ease?: EasingArg): Expr<Key<Vec2>>;
/**
 * A keyframe.
 */
export function key(at: Num, value: Arg<Vec3Value>, ease?: EasingArg): Expr<Key<Vec3Value>>;
/**
 * A keyframe.
 */
export function key(at: Num, value: Arg<Color>, ease?: EasingArg): Expr<Key<Color>>;
/**
 * A keyframe.
 */
export function key(at: Num, value: Arg<string>, ease?: EasingArg): Expr<Key<string>>;
export function key(at: Num, value: AnyArg, ease?: EasingArg): Expr<Key> {
  return call("key", [at, value, ease]);
}

/**
 * The value of keys at \`t\`.
 */
export function keyframes<T extends KeyValue>(
  t: Num,
  ...keys: readonly [Expr<Key<T>>, ...Expr<Key<T>>[]]
): Expr<T>;
/**
 * The value of keys at \`t\`.
 */
export function keyframes<T extends KeyValue>(
  t: Num,
  ease: EasingArg,
  ...keys: readonly [Expr<Key<T>>, ...Expr<Key<T>>[]]
): Expr<T>;
export function keyframes(t: Num, ...rest: readonly AnyArg[]): Expr {
  return call("keyframes", [t, ...rest]);
}
`);
});

test("fails when a signature override names no builtin", () => {
  expect(() => renderExpressions({ builtins: [], globals: [] })).toThrow(
    "The signature override for `keyframes` names no builtin in the table",
  );
});
