import { type JsonSchema, array, object } from "./render-defs.js";

const lineWidth = 100;

export interface BuiltinSchema {
  readonly name: string;
  readonly minArgs: number;
  readonly maxArgs: number | null;
  readonly args: readonly { readonly name: string; readonly kind: string }[];
  readonly returns: string;
  readonly doc: string;
}

export interface GlobalSchema {
  readonly name: string;
  readonly doc: string;
}

export interface ExpressionTables {
  readonly builtins: readonly BuiltinSchema[];
  readonly globals: readonly GlobalSchema[];
}

interface Signature {
  readonly generics?: string;
  readonly params: readonly string[];
  readonly returns: string;
}

/** The signatures of a helper whose arguments the table can't describe. */
export interface SignatureOverride {
  readonly overloads: readonly Signature[];
  readonly implementation: Signature;
  /** What the body passes to `call`, in terms of the implementation's parameters. */
  readonly args: string;
}

/**
 * `keyframes(t, ...keys)` and `keyframes(t, ease, ...keys)` have an optional argument before the
 * rest and are generic over the type of the keys' values, which the table has no notation for.
 * The documentation and the body of an overridden helper still come from the table.
 */
export const signatureOverrides: Readonly<Record<string, SignatureOverride>> = {
  keyframes: {
    overloads: [
      {
        generics: "<T extends KeyValue>",
        params: ["t: Num", "...keys: readonly [Expr<Key<T>>, ...Expr<Key<T>>[]]"],
        returns: "Expr<T>",
      },
      {
        generics: "<T extends KeyValue>",
        params: [
          "t: Num",
          "ease: EasingArg",
          "...keys: readonly [Expr<Key<T>>, ...Expr<Key<T>>[]]",
        ],
        returns: "Expr<T>",
      },
    ],
    implementation: { params: ["t: Num", "...rest: readonly AnyArg[]"], returns: "Expr" },
    args: "[t, ...rest]",
  },
};

const header = `// Generated by tooling/generate-types from definitions/composition.schema.json.
// Do not edit by hand.

`;

/** Names a parameter can't take: reserved words, and `call`, which it would hide. */
const reservedNames = new Set(
  (
    "await break call case catch class const continue debugger default delete do else enum export " +
    "extends false finally for function if implements import in instanceof interface let new null " +
    "package private protected public return static super switch this throw true try typeof var " +
    "void while with yield"
  ).split(" "),
);

/** What a `same` argument and return stand for, one overload each, in this order. */
const sameTypes = [
  { arg: "Num", value: "number" },
  { arg: "Arg<Vec2>", value: "Vec2" },
  { arg: "Arg<Vec3Value>", value: "Vec3Value" },
  { arg: "Arg<Color>", value: "Color" },
  { arg: "Arg<string>", value: "string" },
] as const;

const argTypes: Readonly<Record<string, string>> = {
  number: "Num",
  vec2: "Arg<Vec2>",
  vec3: "Arg<Vec3Value>",
  color: "Arg<Color>",
  string: "Arg<string>",
  text: "Arg<string> | Num",
  easing: "EasingArg",
  key: "Expr<Key>",
  any: "AnyArg",
};

const returnTypes: Readonly<Record<string, string>> = {
  number: "Expr<number>",
  vec2: "Expr<Vec2>",
  vec3: "Expr<Vec3Value>",
  color: "Expr<Color>",
  string: "Expr<string>",
  easing: "Expr<Easing>",
  key: "Expr<Key>",
  any: "Expr<Value>",
};

/** The names of `../expression-core.js` the generated code can use. */
const coreTypes = [
  "AnyArg",
  "Arg",
  "Easing",
  "EasingArg",
  "Key",
  "KeyValue",
  "Num",
  "Value",
  "Vec3Value",
];

/** The names of `@lumiscia/lumen-types` the generated code can use. */
const valueTypes = ["Color", "Vec2"];

const camelCase = (name: string): string =>
  name.replace(/_([a-z])/g, (_, char: string) => char.toUpperCase());

function lookup(table: Readonly<Record<string, string>>, kind: string, owner: string): string {
  const type = table[kind];
  if (type === undefined) {
    throw new Error(
      `\`${owner}\` has the expression kind \`${kind}\`, which has no TypeScript type`,
    );
  }
  return type;
}

/** `text` as a JSDoc comment wrapped to the line width. */
function docComment(text: string): string {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(/\s+/)) {
    if (line !== "" && ` * ${line} ${word}`.length > lineWidth) {
      lines.push(line);
      line = word;
    } else {
      line = line === "" ? word : `${line} ${word}`;
    }
  }
  lines.push(line);
  return `/**\n${lines.map((entry) => ` * ${entry}`).join("\n")}\n */`;
}

/** The declaration on one line when it fits, otherwise with a parameter per line. */
function declaration(name: string, signature: Signature, end: string): string {
  const head = `export function ${name}${signature.generics ?? ""}`;
  const inline = `${head}(${signature.params.join(", ")}): ${signature.returns}${end}`;
  if (inline.length <= lineWidth) {
    return inline;
  }
  const params = signature.params
    .map((param) => (param.startsWith("...") ? `  ${param}` : `  ${param},`))
    .join("\n");
  return `${head}(\n${params}\n): ${signature.returns}${end}`;
}

interface Parameter {
  readonly name: string;
  readonly kind: string;
  readonly optional: boolean;
  readonly rest: boolean;
}

function parameters(builtin: BuiltinSchema): Parameter[] {
  const { args, maxArgs, minArgs, name } = builtin;
  const named = args.map((arg) => {
    const camel = camelCase(arg.name);
    return { name: reservedNames.has(camel) ? `${camel}_` : camel, kind: arg.kind };
  });
  if (maxArgs !== null) {
    return named.map((arg, index) => ({
      ...arg,
      optional: index >= minArgs,
      rest: false,
    }));
  }
  const last = named.at(-1);
  if (last === undefined || named.length - 1 > minArgs) {
    throw new Error(`\`${name}\` repeats its last argument, but has no room for one`);
  }
  const list: Parameter[] = named
    .slice(0, -1)
    .map((arg) => ({ ...arg, optional: false, rest: false }));
  const repeated = (rest: boolean): Parameter => {
    const count = list.length - (named.length - 1);
    return {
      ...last,
      name: count === 0 ? last.name : `${last.name}${count + 1}`,
      optional: false,
      rest,
    };
  };
  while (list.length < minArgs) {
    list.push(repeated(false));
  }
  list.push(repeated(true));
  return list;
}

function parameterText(parameter: Parameter, same: string): string {
  const type = parameter.kind === "same" ? same : lookup(argTypes, parameter.kind, parameter.name);
  if (parameter.rest) {
    return `...${parameter.name}: ${type.includes(" ") ? `(${type})` : type}[]`;
  }
  return `${parameter.name}${parameter.optional ? "?" : ""}: ${type}`;
}

function returnText(builtin: BuiltinSchema, same: string): string {
  if (builtin.returns === "same") {
    return `Expr<${same}>`;
  }
  if (builtin.returns === "key" && same !== "") {
    return `Expr<Key<${same}>>`;
  }
  return lookup(returnTypes, builtin.returns, builtin.name);
}

/** The code of one helper: its overloads, if it has any, and its implementation. */
function renderBuiltin(builtin: BuiltinSchema): string {
  const name = camelCase(builtin.name);
  if (reservedNames.has(name)) {
    throw new Error(`\`${builtin.name}\` can't be a function named \`${name}\``);
  }
  const doc = docComment(builtin.doc);
  const override = signatureOverrides[builtin.name];
  let overloads: readonly Signature[];
  let implementation: Signature;
  let args: string;
  if (override !== undefined) {
    ({ overloads, implementation, args } = override);
  } else {
    const params = parameters(builtin);
    const usesSame = builtin.returns === "same" || params.some((param) => param.kind === "same");
    implementation = {
      params: params.map((param) => parameterText(param, "AnyArg")),
      returns: builtin.returns === "same" ? "Expr<Value>" : returnText(builtin, ""),
    };
    overloads = usesSame
      ? sameTypes.map(({ arg, value }) => ({
          params: params.map((param) => parameterText(param, arg)),
          returns: returnText(builtin, value),
        }))
      : [];
    args = `[${params.map((param) => `${param.rest ? "..." : ""}${param.name}`).join(", ")}]`;
  }
  const signatures = overloads.map((overload) => `${doc}\n${declaration(name, overload, ";")}\n`);
  if (overloads.length === 0) {
    signatures.push(`${doc}\n`);
  }
  return `${signatures.join("")}${declaration(name, implementation, "")} {\n  return call("${builtin.name}", ${args});\n}`;
}

function renderGlobal(global: GlobalSchema): string {
  return `${docComment(global.doc)}\nexport const ${camelCase(global.name)} = new Expr<number>("${global.name}");`;
}

/** Fails when an override names a builtin that is not in the table. */
function checkOverrides(builtins: readonly BuiltinSchema[]): void {
  for (const name of Object.keys(signatureOverrides)) {
    if (!builtins.some((builtin) => builtin.name === name)) {
      throw new Error(`The signature override for \`${name}\` names no builtin in the table`);
    }
  }
}

function renderImport(names: readonly string[], source: string): string {
  const inline = `import { ${names.join(", ")} } from "${source}";`;
  return inline.length <= lineWidth
    ? inline
    : `import {\n${names.map((name) => `  ${name},`).join("\n")}\n} from "${source}";`;
}

function renderImports(code: string): string {
  const used = (name: string): boolean => new RegExp(`\\b${name}\\b`).test(code);
  const typed = (names: readonly string[]): string[] =>
    names.filter(used).map((name) => `type ${name}`);
  const imports = [
    { names: typed(valueTypes), source: "@lumiscia/lumen-types" },
    {
      names: [...["call", "Expr"].filter(used), ...typed(coreTypes)],
      source: "../expression-core.js",
    },
  ];
  return imports
    .filter(({ names }) => names.length > 0)
    .map(({ names, source }) => renderImport(names, source))
    .join("\n\n");
}

/** The contents of `lumen-shared/src/generated/expressions.ts`. */
export function renderExpressions({ builtins, globals }: ExpressionTables): string {
  checkOverrides(builtins);
  const body = [...globals.map(renderGlobal), ...builtins.map(renderBuiltin)].join("\n\n");
  const code = body.replace(/\/\*\*\n(?: \*.*\n)* \*\/\n/g, "");
  return `${header}${renderImports(code)}\n\n${body}\n`;
}

const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** The contents of `lumen-shared/src/generated/arity.ts`. */
export function renderArity({ builtins }: ExpressionTables): string {
  const entries = builtins.map(
    ({ name, minArgs, maxArgs }) =>
      `  ${identifier.test(name) ? name : JSON.stringify(name)}: [${minArgs}, ${maxArgs ?? "null"}],\n`,
  );
  return `${header}import type { ExpressionBuiltinName } from "@lumiscia/lumen-types";

/** The fewest and the most arguments each builtin takes; \`null\` is no upper limit. */
export const builtinArity: Readonly<
  Record<ExpressionBuiltinName, readonly [min: number, max: number | null]>
> = {
${entries.join("")}};
`;
}

const text = (value: unknown): string => (typeof value === "string" ? value : "");

/** The builtins and globals of `x-lumen-expressions`. */
export function expressionTables(schema: JsonSchema): ExpressionTables {
  const expressions = object(schema["x-lumen-expressions"]);
  return {
    builtins: array(expressions.builtins).map((entry) => {
      const builtin = object(entry);
      return {
        name: text(builtin.name),
        minArgs: Number(builtin.minArgs),
        maxArgs: builtin.maxArgs === null ? null : Number(builtin.maxArgs),
        args: array(builtin.args).map((arg) => ({
          name: text(object(arg).name),
          kind: text(object(arg).kind),
        })),
        returns: text(builtin.returns),
        doc: text(builtin.doc),
      };
    }),
    globals: array(expressions.globals).map((entry) => ({
      name: text(object(entry).name),
      doc: text(object(entry).doc),
    })),
  };
}
